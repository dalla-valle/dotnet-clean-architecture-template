namespace Microservice_Name_Token.Api.Mapper;

using System.Diagnostics;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using System.Collections.Generic;
using System.Linq;

/// <summary>
/// Represents custom problem details for API error responses.
/// </summary>
public class CustomProblemDetails
{
    /// <summary>
    /// Gets or sets the URI reference that identifies the problem type.
    /// </summary>
    public string? Type { get; set; }

    /// <summary>
    /// Gets or sets a short, human-readable summary of the problem type.
    /// </summary>
    public string? Title { get; set; }

    /// <summary>
    /// Gets or sets the HTTP status code generated by the origin server for this occurrence of the problem.
    /// </summary>
    public int Status { get; set; }

    /// <summary>
    /// Gets or sets the unique identifier for the request trace.
    /// </summary>
    public string? TraceId { get; set; }

    /// <summary>
    /// Gets or sets the list of validation errors.
    /// </summary>
    public List<ValidationError>? Errors { get; set; }

    /// <summary>
    /// Builds a <see cref="CustomProblemDetails"/> instance from the specified <see cref="ModelStateDictionary"/>.
    /// </summary>
    /// <param name="modelStateDictionary">The model state dictionary containing validation errors.</param>
    /// <returns>A <see cref="CustomProblemDetails"/> instance populated with validation errors.</returns>
    public static CustomProblemDetails Build(ModelStateDictionary modelStateDictionary) =>
        new ()
        {
            Type = "https://tools.ietf.org/html/rfc7231#section-6.5.1",
            Title = "One or more validation errors occurred.",
            Status = StatusCodes.Status400BadRequest,
            TraceId = Activity.Current?.Id,
            Errors = modelStateDictionary
                .Where(kvp => kvp.Value?.Errors.Count > 0)
                .Select(_ => new ValidationError(_.Key, _.Value!.Errors.Select(_ => _.ErrorMessage)))
                .ToList(),
        };
}